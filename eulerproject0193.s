              Pattern based on uploaded PE154 TSE/Python macro.

  Notes:
  - Creates pe193.py in the current working directory
  - Runs pe193.py with:
      g:\language\computer\python\python\python.exe
  - Reads result from pe193result.txt
  - Uses one final Warn() only
  - Copies only the bare final answer to clipboard
