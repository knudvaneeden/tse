// -------------------------------------------------------
// Proc: WritePyScript
//   Creates a Python 3 script that reads the data file,
//   computes e * log(b) for each pair, and writes the
//   winning 1-based line number to result_path.
// -------------------------------------------------------
proc WritePyScript(string scr_path, string dat_path, string res_path)
    integer py_buf

    py_buf = CreateTempBuffer()
    GotoBufferId(py_buf)

    AddLine("import math")
    AddLine("best_line = 0")
    AddLine("best_sc = 0.0")
    AddLine("with open(dat_path) as fh:")
    AddLine("    for ln_num, row in enumerate(fh, 1):")
    AddLine("        b, e = map(int, row.strip().split(chr(44)))")
    AddLine("        sc = e * math.log(b)")
    AddLine("        if sc > best_sc:")
    AddLine("            best_sc = sc")
    AddLine("            best_line = ln_num")
    AddLine("with open(res_path, chr(119)) as out:")
    AddLine("    out.write(str(best_line))")

    SaveAs(scr_path, _OVERWRITE_)
    AbandonFile(py_buf)
end

// -------------------------------------------------------
// Main
// -------------------------------------------------------
proc Main()
    string  dat_path[255]
    string  scr_path[255]
    string  res_path[255]
    string  cmd_str[255]
    string  answer_str[20]
    integer res_buf

    // Build paths in the system TEMP directory
    dat_path = GetEnvStr("TEMP") + "\pe099_data.txt"
    scr_path = GetEnvStr("TEMP") + "\pe099_solve.py"
    res_path = GetEnvStr("TEMP") + "\pe099_result.txt"

    // Step 1: write the 1000-line data file to disk
    WriteDataFile(dat_path)

    // Step 2: write the Python solver script to disk
    WritePyScript(scr_path, dat_path, res_path)

    // Step 3: patch the Python script paths into it
    //   (we inject dat_path and res_path as variables at top of file)
    //   Open the script, prepend two assignment lines, re-save.
    res_buf = EditFile(scr_path)
    GotoBufferId(res_buf)
    BegFile()
    InsertLine("res_path = r" + '"' + res_path + '"')
    BegFile()
    InsertLine("dat_path = r" + '"' + dat_path + '"')
    SaveAs(scr_path, _OVERWRITE_)
    AbandonFile(res_buf)

    // Step 4: run the Python script; wait for completion
    // cmd_str = "python " + Chr(34) + scr_path + Chr(34)
    cmd_str = "g:\language\computer\python\python\python.exe " + Chr(34) + scr_path + Chr(34)
    Dos(cmd_str, _DEFAULT_)

    // Step 5: if result absent, try python3
    if not FileExists(res_path)
        cmd_str = "python3 " + Chr(34) + scr_path + Chr(34)
        Dos(cmd_str, _DEFAULT_)
    endif

    // Step 6: guard: if still no result, report error
    if not FileExists(res_path)
        Warn("PE #99 Error: Python did not write a result file.")
        Return()
    endif

    // Step 7: read the answer line number from the result file
    res_buf = EditFile(res_path)
    GotoBufferId(res_buf)
    BegFile()
    answer_str = GetText(1, CurrLineLen())
    AbandonFile(res_buf)

    // Step 8: show the answer and put it on the clipboard
    //   Only the bare answer (e.g. "709") goes to the clipboard.
    Warn("Project Euler #99 answer: line " + answer_str)
    CopyToWinClip(answer_str)
end
