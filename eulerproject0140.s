      Return( "49392" )
    WHEN 12
      Return( "95760" )
  ENDCASE
  cycleCountI = ( targetIndexI - 1 ) / 6
  remainderI = ( targetIndexI - 1 ) mod 6
  WHILE cycleCountI > 1
    nextS = ProcMakeNextNugget( seed1PrevS, seed1CurrS )
    seed1PrevS = seed1CurrS
    seed1CurrS = nextS
    //
    nextS = ProcMakeNextNugget( seed2PrevS, seed2CurrS )
    seed2PrevS = seed2CurrS
