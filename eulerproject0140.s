    //
    nextS = ProcMakeNextNugget( seed6PrevS, seed6CurrS )
    seed6PrevS = seed6CurrS
    seed6CurrS = nextS
    //
    cycleCountI = cycleCountI - 1
  ENDWHILE
  CASE remainderI
    WHEN 0
      Return( seed1CurrS )
    WHEN 1
      Return( seed2CurrS )
    WHEN 2
      Return( seed3CurrS )
    WHEN 3
      Return( seed4CurrS )
    WHEN 4
      Return( seed5CurrS )
    OTHERWISE
