// Algorithm: bottom-up dynamic programming.
//   new[j] = triangle[row][j] + max( below[j], below[j+1] )
//
// Key design:
//   - triId: ONE TOKEN PER LINE. Row k starts at line k*(k-1)/2+1.
//     Avoids TSE GetText column > 255 limitation entirely.
//   - dpBufId: lines 1..100=below, lines 101..200=current.
//   - No EmptyBuffer. CreateTempBuffer gives 1 blank line used as line 1.
//
// Expected answer: 7273

// Row k starts at line k*(k-1)/2 + 1 in triId. Token j is at that line + j-1.
integer proc GetTriTok( integer triId, integer lineNo, integer nTok )
    integer startLine
    string  tok[8]
    startLine = lineNo * (lineNo - 1) / 2 + 1
    GotoBufferId( triId )
    GotoLine( startLine + nTok - 1 )
    tok = GetText( 1, CurrLineLen() )
    return( Val( tok ) )
end

